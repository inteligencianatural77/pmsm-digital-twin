# ---------------------------------------------------------------------------
# PI reconstruction diagnostic
# ---------------------------------------------------------------------------

def analyze_pi_reconstruction(
    rows: list[dict],
) -> tuple[list[dict], list[dict]]:
    """
    Reconstruct the unsaturated speed-controller PI output:

        iq_ref ~= kp * error + ki * int_w

    This is only a diagnostic consistency check.

    Because the actual controller saturates iq_ref, the equality is not
    expected to hold when saturation occurs.
    """
    diagnostics: list[dict] = []

    for row in rows:
        iq_raw = (
            row["kp"] * row["error"]
            + row["ki"] * row["int_w"]
        )

        residual = row["iq_ref"] - iq_raw

        diagnostics.append(
            {
                "candidate": row["candidate"],
                "scenario": row["scenario"],
                "transition": row["transition"],
                "t": row["t"],
                "iq_ref": row["iq_ref"],
                "iq_raw_reconstructed": iq_raw,
                "residual": residual,
                "abs_residual": abs(residual),
                "abs_iq": row["abs_iq"],
            }
        )

    unsaturated = [
        row
        for row in diagnostics
        if row["abs_iq"] < 79.5
    ]

    residuals = [row["abs_residual"] for row in unsaturated]

    summary = [
        {
            "samples_total": len(diagnostics),
            "samples_below_physical_current_limit": len(unsaturated),
            "mean_abs_residual": mean(residuals),
            "p95_abs_residual": percentile(residuals, 95),
            "max_abs_residual": max(residuals)
            if residuals
            else float("nan"),
        }
    ]

    return diagnostics, summary


