def analyze_input_statistics(rows: list[dict]) -> list[dict]:
    """
    Statistics for the proposed ANFIS inputs:

        z = [error, delta_error, abs_iq]
    """
    fields = [
        "error",
        "delta_error",
        "abs_iq",
    ]

    output_rows: list[dict] = []

    for candidate in sorted({row["candidate"] for row in rows}):
        candidate_rows = [
            row for row in rows
            if row["candidate"] == candidate
        ]

        for scenario in sorted(
            {row["scenario"] for row in candidate_rows}
        ):
            subset = [
                row
                for row in candidate_rows
                if row["scenario"] == scenario
            ]

            output = {
                "candidate": candidate,
                "scenario": scenario,
                "samples": len(subset),
            }

            for field in fields:
                values = [row[field] for row in subset]

                output[f"{field}_min"] = min(values)
                output[f"{field}_p01"] = percentile(values, 1)
                output[f"{field}_p25"] = percentile(values, 25)
                output[f"{field}_median"] = percentile(values, 50)
                output[f"{field}_p75"] = percentile(values, 75)
                output[f"{field}_p99"] = percentile(values, 99)
                output[f"{field}_max"] = max(values)
                output[f"{field}_mean"] = mean(values)
                output[f"{field}_std"] = float(
                    np.std(np.asarray(values, dtype=float))
                )

            output_rows.append(output)

    return output_rows


