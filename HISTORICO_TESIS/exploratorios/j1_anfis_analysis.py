def analyze_candidates(rows: list[dict]) -> list[dict]:
    """Summarize tracking performance for each controller candidate."""
    candidates = sorted(
        {
            row["candidate"]
            for row in rows
        }
    )

    output_rows: list[dict] = []

    for candidate in candidates:
        subset = [
            row
            for row in rows
            if row["candidate"] == candidate
        ]

        errors = [row["error"] for row in subset]
        abs_errors = [abs(value) for value in errors]
        iq_values = [row["abs_iq"] for row in subset]

        kp_values = {row["kp"] for row in subset}
        ki_values = {row["ki"] for row in subset}

        if len(kp_values) != 1 or len(ki_values) != 1:
            raise ValueError(
                f"Candidate {candidate} has inconsistent PI gains"
            )

        output_rows.append(
            {
                "candidate": candidate,
                "kp": next(iter(kp_values)),
                "ki": next(iter(ki_values)),
                "samples": len(subset),
                "mae_error": mean(abs_errors),
                "rmse_error": rmse(errors),
                "max_abs_error": max(abs_errors),
                "p95_abs_error": percentile(abs_errors, 95),
                "max_abs_iq": max(iq_values),
                "fraction_above_79_5A": (
                    sum(value > 79.5 for value in iq_values)
                    / len(iq_values)
                ),
            }
        )

    return output_rows


def analyze_integral_diagnostic(rows: list[dict]) -> list[dict]:
    """
    Determine whether int_w carries information not directly observable
    from the proposed ANFIS inputs.

    Correlations are diagnostic only; they do not establish causality.
    """
    fields = [
        "error",
        "delta_error",
        "abs_iq",
        "int_w",
    ]

    output_rows: list[dict] = []

    for candidate in sorted({row["candidate"] for row in rows}):
        subset = [
            row for row in rows
            if row["candidate"] == candidate
        ]

        output = {
            "candidate": candidate,
            "samples": len(subset),
        }

        for field in fields:
            values = [row[field] for row in subset]

            output[f"{field}_mean"] = mean(values)
            output[f"{field}_std"] = float(
                np.std(np.asarray(values, dtype=float))
            )

        for field in [
            "error",
            "delta_error",
            "abs_iq",
        ]:
            output[f"corr_int_w_{field}"] = correlation(
                [row["int_w"] for row in subset],
                [row[field] for row in subset],
            )

        output_rows.append(output)

    return output_rows


# ---------------------------------------------------------------------------
# Observable-state overlap diagnostic
# ---------------------------------------------------------------------------

def analyze_state_overlap(rows: list[dict]) -> list[dict]:
    """
    Coarse state-overlap diagnostic.

    The proposed ANFIS observable state is:

        [error, delta_error, abs_iq]

    The analysis bins these variables and checks how much int_w varies
    inside regions that appear similar in the proposed observable space.

    This does NOT prove that the input set is sufficient or insufficient.
    It is a diagnostic for possible hidden-state dependence.
    """
    observable_fields = [
        "error",
        "delta_error",
        "abs_iq",
    ]

    # Quantization widths.
    # They are intentionally coarse diagnostic bins, not physical thresholds.
    BIN_WIDTHS = {
        "error": 0.5,
        "delta_error": 0.05,
        "abs_iq": 2.0,
    }

    def bin_value(value: float, width: float) -> int:
        return math.floor(value / width)

    groups = defaultdict(list)

    for row in rows:
        key = tuple(
            bin_value(row[field], BIN_WIDTHS[field])
            for field in observable_fields
        )

        groups[key].append(row)

    output_rows: list[dict] = []

    for key, group in groups.items():
        if len(group) < 2:
            continue

        int_values = [row["int_w"] for row in group]

        candidates = sorted({
            row["candidate"]
            for row in group
        })

        scenarios = sorted({
            row["scenario"]
            for row in group
        })

        output_rows.append(
            {
                "error_bin": key[0],
                "delta_error_bin": key[1],
                "abs_iq_bin": key[2],
                "samples": len(group),
                "candidate_count": len(candidates),
                "scenario_count": len(scenarios),
                "int_w_min": min(int_values),
                "int_w_max": max(int_values),
                "int_w_range": max(int_values) - min(int_values),
                "int_w_std": float(
                    np.std(np.asarray(int_values, dtype=float))
                ),
                "candidate_values": "|".join(candidates),
                "scenario_values": "|".join(scenarios),
            }
        )

    output_rows.sort(
        key=lambda row: row["int_w_range"],
        reverse=True,
    )

    return output_rows


