def analyze_transitions(rows: list[dict]) -> list[dict]:
    """Analyze each reference transition separately.

    The initial pre_profile segment is intentionally excluded because
    it is the preconditioned state before the reference profile starts,
    not a reference transition.
    """
    output_rows: list[dict] = []

    transitions = sorted(
        {
            row["transition"]
            for row in rows
            if row["transition"] != "pre_profile"
        }
    )

    for transition in transitions:
        subset = [
            row
            for row in rows
            if row["transition"] == transition
        ]

        errors = [row["error"] for row in subset]
        abs_errors = [abs(value) for value in errors]
        iq_values = [row["abs_iq"] for row in subset]

        output_rows.append(
            {
                "transition": transition,
                "samples": len(subset),
                "mae_error": mean(abs_errors),
                "rmse_error": rmse(errors),
                "max_abs_error": max(abs_errors),
                "p95_abs_error": percentile(abs_errors, 95),
                "max_abs_iq": max(iq_values),
                "fraction_above_79_5A": (
                    sum(value > 79.5 for value in iq_values)
                    / len(iq_values)
                ),
            }
        )

    return output_rows


