def read_csv_rows(path: Path) -> list[dict[str, str]]:
    """Read a CSV file using only the Python standard library."""
    if not path.exists():
        raise FileNotFoundError(f"No existe el archivo: {path}")

    with path.open("r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)

        if reader.fieldnames is None:
            raise ValueError(f"El CSV no contiene encabezados: {path}")

        return list(reader)


def write_csv(
    path: Path,
    fieldnames: list[str],
    rows: list[dict],
) -> None:
    """Write a CSV file."""
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=fieldnames,
            extrasaction="ignore",
        )
        writer.writeheader()

        for row in rows:
            writer.writerow(row)


def finite_float(value: str, field: str, row_number: int) -> float:
    """Convert a CSV field to float and reject NaN/Inf."""
    try:
        x = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(
            f"Valor no numérico en fila {row_number}, "
            f"campo '{field}': {value!r}"
        ) from exc

    if not math.isfinite(x):
        raise ValueError(
            f"Valor no finito en fila {row_number}, "
            f"campo '{field}': {value!r}"
        )

    return x


def mean(values: list[float]) -> float:
    if not values:
        return float("nan")
    return float(np.mean(values))


def rmse(values: list[float]) -> float:
    if not values:
        return float("nan")

    arr = np.asarray(values, dtype=float)
    return float(np.sqrt(np.mean(arr**2)))


def percentile(values: list[float], q: float) -> float:
    if not values:
        return float("nan")
    return float(np.percentile(np.asarray(values, dtype=float), q))


def correlation(x: list[float], y: list[float]) -> float:
    """
    Pearson correlation.

    Returns NaN when one variable has zero variance or there are
    fewer than two observations.
    """
    if len(x) < 2 or len(y) < 2:
        return float("nan")

    xa = np.asarray(x, dtype=float)
    ya = np.asarray(y, dtype=float)

    sx = float(np.std(xa))
    sy = float(np.std(ya))

    if sx == 0.0 or sy == 0.0:
        return float("nan")

    return float(np.corrcoef(xa, ya)[0, 1])


def fmt(value: float, digits: int = 9) -> str:
    if not math.isfinite(value):
        return "nan"
    return f"{value:.{digits}f}"


