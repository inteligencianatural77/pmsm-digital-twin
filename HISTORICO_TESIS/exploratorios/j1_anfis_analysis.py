def load_trajectories() -> list[dict]:
    """Load and convert the J1 trajectory CSV."""
    raw_rows = read_csv_rows(TRAJECTORY_FILE)

    if not raw_rows:
        raise ValueError("El archivo de trayectorias está vacío.")

    missing = [
        column
        for column in REQUIRED_TRAJECTORY_COLUMNS
        if column not in raw_rows[0]
    ]

    if missing:
        raise ValueError(
            "Faltan columnas requeridas en j1_temporal_trajectories.csv: "
            + ", ".join(missing)
        )

    numeric_columns = [
        column
        for column in REQUIRED_TRAJECTORY_COLUMNS
        if column not in {"candidate", "scenario", "transition"}
    ]

    rows: list[dict] = []

    for row_number, raw in enumerate(raw_rows, start=2):
        row = dict(raw)

        for column in numeric_columns:
            row[column] = finite_float(
                raw[column],
                column,
                row_number,
            )

        rows.append(row)

    return rows


