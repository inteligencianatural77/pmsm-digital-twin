def analyze_scenarios(rows: list[dict]) -> list[dict]:
    """Aggregate error/current behavior by friction scenario."""
    output_rows: list[dict] = []

    for scenario in sorted({row["scenario"] for row in rows}):
        subset = [
            row for row in rows
            if row["scenario"] == scenario
        ]

        errors = [abs(row["error"]) for row in subset]
        iq_values = [row["abs_iq"] for row in subset]

        output_rows.append(
            {
                "scenario": scenario,
                "samples": len(subset),
                "mae_error": mean(errors),
                "rmse_error": rmse(
                    [row["error"] for row in subset]
                ),
                "max_abs_error": max(errors),
                "p95_abs_error": percentile(errors, 95),
                "mean_abs_iq": mean(iq_values),
                "max_abs_iq": max(iq_values),
                "fraction_above_79_5A": (
                    sum(value > 79.5 for value in iq_values)
                    / len(iq_values)
                ),
            }
        )

    return output_rows


